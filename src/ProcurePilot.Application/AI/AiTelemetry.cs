using System.Diagnostics;
using System.Diagnostics.Metrics;

namespace ProcurePilot.Application.AI;

public static class AiTelemetry
{
    public const string ActivitySourceName = "ProcurePilot.AI";
    public const string MeterName = "ProcurePilot.AI";

    public static readonly ActivitySource ActivitySource = new(ActivitySourceName, "1.0.0");
    public static readonly Meter Meter = new(MeterName, "1.0.0");

    private static readonly Counter<long> AnalysisCounter = Meter.CreateCounter<long>(
        "ai.analysis.count",
        description: "Number of AI analyses performed");

    private static readonly Histogram<double> DurationHistogram = Meter.CreateHistogram<double>(
        "ai.analysis.duration",
        unit: "ms",
        description: "Duration of AI analysis execution in milliseconds");

    private static readonly Counter<long> PromptTokenCounter = Meter.CreateCounter<long>(
        "ai.analysis.tokens.prompt",
        description: "Total input/prompt tokens consumed by AI analysis");

    private static readonly Counter<long> CompletionTokenCounter = Meter.CreateCounter<long>(
        "ai.analysis.tokens.completion",
        description: "Total output/completion tokens generated by AI analysis");

    private static readonly Counter<long> TotalTokenCounter = Meter.CreateCounter<long>(
        "ai.analysis.tokens.total",
        description: "Total tokens processed by AI analysis");

    public static void RecordAnalysis(
        string status,
        string model,
        string analysisType,
        double durationMs,
        int? promptTokens = null,
        int? completionTokens = null,
        int? totalTokens = null)
    {
        var tags = new TagList
        {
            { "status", status },
            { "model", model },
            { "analysis_type", analysisType }
        };

        AnalysisCounter.Add(1, tags);
        DurationHistogram.Record(durationMs, tags);

        if (promptTokens.HasValue)
        {
            PromptTokenCounter.Add(promptTokens.Value, tags);
        }

        if (completionTokens.HasValue)
        {
            CompletionTokenCounter.Add(completionTokens.Value, tags);
        }

        if (totalTokens.HasValue)
        {
            TotalTokenCounter.Add(totalTokens.Value, tags);
        }
    }
}
